# src/evidence/evidence.py
"""Evidence utilities – construct audit‑trail entries that are fully
lineage‑aware.

The output schema (JSON) follows the MVP description:

```json
{
  "transaction_id": "string",
  "anomaly_score": 0.42,
  "reliability_indicator": "high",
  "ml_explanation": {"shap": {"feature": "value", ...}},
  "rule_explanations": [
    {"flag": "duplicate_detection", "explanation": "...", "limitation": null},
    ...
  ],
  "limitations": [],
  "evidence": {
    "source_file": "path/to/file.csv",
    "source_record_id": 123,
    "source_document": null,
    "extraction_method": "csv ingestion",
    "ingestion_timestamp": "2026-09-27T00:10:05+05:30"
  },
  "auditor_disposition": null
}
```
"""

from datetime import datetime
from typing import Any, Dict, List


def build_audit_record(
    row: Dict[str, Any],
    anomaly_score: float,
    reliability_indicator: str,
    ml_explanation: Dict[str, Any] | None,
    rule_explanations: List[Dict[str, Any]] | None,
    limitations: List[str] | None,
    source_file: str,
    source_record_id: int,
) -> Dict[str, Any]:
    """Create a single audit‑trail record.

    Parameters
    ----------
    row: dict
        Original canonical row (keys include ``transaction_id`` etc.).
    anomaly_score: float
        Combined normalized anomaly score (0‑1).
    reliability_indicator: str
        Human‑readable reliability label (e.g. ``"high"``, ``"medium"``).
    ml_explanation: dict | None
        SHAP contribution mapping per feature.
    rule_explanations: list[dict] | None
        Explanations generated by the rule‑explain module.
    limitations: list[str] | None
        Any limitation messages attached to this flag (e.g. Benford not run).
    source_file: str
        Path of the file the row originated from.
    source_record_id: int
        Row number or primary key that identifies the record in the source.
    """
    evidence = {
        "source_file": source_file,
        "source_record_id": source_record_id,
        "source_document": None,
        "extraction_method": "csv ingestion",
        "ingestion_timestamp": datetime.now().isoformat(),
    }

    return {
        "transaction_id": row.get("transaction_id"),
        "anomaly_score": anomaly_score,
        "reliability_indicator": reliability_indicator,
        "ml_explanation": ml_explanation,
        "rule_explanations": rule_explanations or [],
        "limitations": limitations or [],
        "evidence": evidence,
        "auditor_disposition": None,
    }
